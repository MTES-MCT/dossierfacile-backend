package fr.dossierfacile.api.pdfgenerator.service.templates.dossier;

import org.apache.commons.lang3.StringUtils;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.cos.COSName;
import org.apache.pdfbox.multipdf.LayerUtility;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.PDResources;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.graphics.PDXObject;
import org.apache.pdfbox.pdmodel.graphics.form.PDFormXObject;
import org.apache.pdfbox.pdmodel.graphics.image.PDImageXObject;
import org.apache.pdfbox.text.PDFTextStripper;
import org.apache.pdfbox.util.Matrix;
import org.springframework.stereotype.Component;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Reads the pages of a watermarked piece, which is a PDF:
 * <ul>
 *     <li>the watermark generator writes each page as a single JPEG image, and this class returns that image without
 *     decoding or re-encoding it;</li>
 *     <li>this class returns any other page, such as a sworn statement generated by DossierFacile, as a PDF page, so
 *     that its text remains a text.</li>
 * </ul>
 */
@Component
public class PieceExtractor {

    public List<PieceContent> extract(InputStream input) throws IOException {
        byte[] pdf = input.readAllBytes();
        try (PDDocument document = Loader.loadPDF(pdf)) {
            List<PieceContent> pages = new ArrayList<>();
            for (int number = 1; number <= document.getNumberOfPages(); number++) {
                PDPage page = document.getPage(number - 1);
                Optional<PieceContent> image = singleJpegImage(page);
                pages.add(image.isPresent() ? image.get() : pdfPage(pdf, document, page, number));
            }
            return pages;
        }
    }

    private PieceContent pdfPage(byte[] pdf, PDDocument document, PDPage page, int number) throws IOException {
        String text = text(document, number);
        PDRectangle box = page.getCropBox();
        if (page.getRotation() % 360 == 0) {
            return new PieceContent(pdf, number, box.getWidth(), box.getHeight(), text);
        }
        boolean sideways = page.getRotation() % 180 != 0;
        PDRectangle upright = sideways ? new PDRectangle(box.getHeight(), box.getWidth()) : new PDRectangle(box.getWidth(), box.getHeight());
        return new PieceContent(straighten(document, page, upright), 1, upright.getWidth(), upright.getHeight(), text);
    }

    /**
     * Copies a rotated page to a page without rotation, with the same display. The HTML engine and
     * {@link LayerUtility} both stretch a page that has a rotation.
     */
    private byte[] straighten(PDDocument document, PDPage page, PDRectangle size) throws IOException {
        int rotation = page.getRotation();
        PDRectangle box = page.getCropBox();
        Matrix matrix = switch (rotation) {
            case 90 -> new Matrix(0, -1, 1, 0, 0, box.getWidth());
            case 180 -> new Matrix(-1, 0, 0, -1, box.getWidth(), box.getHeight());
            default -> new Matrix(0, 1, -1, 0, box.getHeight(), 0);
        };
        try (PDDocument straightened = new PDDocument()) {
            // The import must ignore the rotation. Nothing saves this document, and the finally block restores the rotation.
            page.setRotation(0);
            PDFormXObject form = new LayerUtility(straightened).importPageAsForm(document, page);
            PDPage uprightPage = new PDPage(size);
            straightened.addPage(uprightPage);
            try (PDPageContentStream content = new PDPageContentStream(straightened, uprightPage)) {
                content.transform(matrix);
                content.transform(Matrix.getTranslateInstance(-page.getMediaBox().getLowerLeftX(), -page.getMediaBox().getLowerLeftY()));
                content.drawForm(form);
            }
            ByteArrayOutputStream pdf = new ByteArrayOutputStream();
            straightened.save(pdf);
            return pdf.toByteArray();
        } finally {
            page.setRotation(rotation);
        }
    }

    private String text(PDDocument document, int number) throws IOException {
        PDFTextStripper stripper = new PDFTextStripper();
        stripper.setSortByPosition(true);
        stripper.setStartPage(number);
        stripper.setEndPage(number);
        return StringUtils.normalizeSpace(stripper.getText(document));
    }

    private Optional<PieceContent> singleJpegImage(PDPage page) throws IOException {
        PDResources resources = page.getResources();
        if (resources == null || page.getRotation() % 360 != 0) {
            return Optional.empty();
        }
        PDImageXObject image = null;
        for (COSName name : resources.getXObjectNames()) {
            PDXObject xObject = resources.getXObject(name);
            if (!(xObject instanceof PDImageXObject candidate) || image != null) {
                return Optional.empty();
            }
            image = candidate;
        }
        if (image == null || image.getSoftMask() != null || image.getMask() != null) {
            return Optional.empty();
        }
        List<COSName> filters = image.getStream().getFilters();
        if (filters.size() != 1 || !COSName.DCT_DECODE.equals(filters.get(0))) {
            return Optional.empty();
        }
        // Stop before the DCT filter, because the raw stream is the JPEG file itself.
        try (InputStream jpeg = image.getStream().createInputStream(List.of(COSName.DCT_DECODE.getName()))) {
            return Optional.of(PieceContent.image(jpeg.readAllBytes(), image.getWidth(), image.getHeight()));
        }
    }
}
