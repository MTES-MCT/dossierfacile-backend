package fr.dossierfacile.api.pdfgenerator.service.templates;

import fr.dossierfacile.api.pdfgenerator.service.interfaces.PdfSignatureService;
import fr.dossierfacile.api.pdfgenerator.service.interfaces.PdfTemplate;
import fr.dossierfacile.api.pdfgenerator.util.Fonts;
import fr.dossierfacile.api.pdfgenerator.util.Utility;
import lombok.AccessLevel;
import lombok.RequiredArgsConstructor;
import lombok.Setter;
import lombok.extern.slf4j.Slf4j;
import org.apache.commons.lang3.StringUtils;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType0Font;
import org.springframework.context.MessageSource;
import org.springframework.context.i18n.LocaleContextHolder;
import org.springframework.stereotype.Service;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.time.Clock;
import java.time.LocalDate;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.MatchResult;
import java.util.regex.Pattern;

/**
 * Common layout of every sworn statement ("Attestation sur l'honneur") generated by DossierFacile.
 * A new statement only has to provide an {@link AttestationContent}.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class AttestationPdfTemplate implements PdfTemplate<AttestationContent> {

    // Layout of the mockup: A4 page, values in points, vertical positions measured from the top of the page
    private static final float MARGIN_X = 40;
    private static final float MARGIN_Y = 50;
    private static final float TITLE_TOP = 120;
    private static final float TITLE_FONT_SIZE = 28;
    private static final float TITLE_LINE_HEIGHT = 36;
    private static final float TITLE_TO_BODY = 60;
    private static final float BODY_FONT_SIZE = 18;
    private static final float BODY_LINE_HEIGHT = 28;
    private static final float PARAGRAPH_SPACING = 24;

    private static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("dd/MM/yyyy");
    // The attestation is dated in French time, whatever the time zone of the server
    private static final ZoneId FRENCH_TIME = ZoneId.of("Europe/Paris");
    // A base character followed by its combining marks
    private static final Pattern GRAPHEME = Pattern.compile("\\P{M}\\p{M}*+");
    // Line breaks, tabs and thin spaces become a space. The no-break space is not matched by \s and is kept
    private static final Pattern WHITESPACE = Pattern.compile("[\\s\\u2009\\u202F]+");
    // Keeps two words on the same line, as before a colon in French. It is drawn as a space
    private static final char NO_BREAK_SPACE = ' ';

    private final MessageSource messageSource;
    private final PdfSignatureService pdfSignatureService;
    // Replaced in tests to get a known date
    @Setter(AccessLevel.PACKAGE)
    private Clock clock = Clock.systemUTC();

    @Override
    public InputStream render(AttestationContent content) throws Exception {
        ByteArrayOutputStream outputStream = new ByteArrayOutputStream();
        try (PDDocument document = PdfFileTemplate.ATTESTATION.load()) {
            String personName = clean(content.personName());
            String explanation = clean(content.explanation());
            String date = message("document.attestation.date", LocalDate.ofInstant(clock.instant(), FRENCH_TIME).format(DATE_FORMAT));
            String signature = message("document.attestation.signature");
            try (PageWriter writer = new PageWriter(document)) {
                writer.title(message("document.attestation.title"));
                writer.paragraph(message("document.attestation.certify", personName));
                writer.paragraph("\"" + clean(content.statement()) + "\"");
                if (!explanation.isEmpty()) {
                    writer.paragraph(message("document.attestation.explanation", explanation));
                }
                // The date, the signature and the name stay on the same page
                writer.keepTogether(writer.heightOf(date) + PARAGRAPH_SPACING + writer.heightOf(signature, personName));
                writer.paragraph(date);
                writer.paragraph(signature, personName);
                if (!writer.skippedCharacters.isEmpty()) {
                    log.warn("Characters missing from the fonts were not printed on the attestation: {}", writer.skippedCharacters);
                }
            }
            pdfSignatureService.signAndSave(document, outputStream);
        } catch (Exception e) {
            log.error("Error on attestation pdf creation", e);
            throw e;
        }
        return new ByteArrayInputStream(outputStream.toByteArray());
    }

    private String message(String code, Object... args) {
        return messageSource.getMessage(code, args, LocaleContextHolder.getLocale());
    }

    private static String clean(String text) {
        return text == null ? "" : WHITESPACE.matcher(text).replaceAll(" ").trim();
    }

    /**
     * Writes text from top to bottom and adds a page when the current one is full.
     */
    private static final class PageWriter implements AutoCloseable {

        private final PDDocument document;
        private final PDType0Font regularFont;
        private final PDType0Font boldFont;
        // Used for the characters missing from Marianne: other alphabets, then emojis
        private final PDType0Font fallbackFont;
        private final PDType0Font emojiFont;
        private final float pageHeight;
        private final float contentWidth;
        // Code points found in none of the fonts
        private final Set<String> skippedCharacters = new TreeSet<>();
        private PDPageContentStream contentStream;
        // Distance between the top of the page and the top of the next line
        private float cursor;

        PageWriter(PDDocument document) throws IOException {
            this.document = document;
            this.regularFont = load(Fonts.MARIANNE_REGULAR, document);
            this.boldFont = load(Fonts.MARIANNE_BOLD, document);
            this.fallbackFont = load(Fonts.ARIAL_NOVA_LIGHT, document);
            this.emojiFont = load(Fonts.NOTO_EMOJI_MEDIUM, document);
            PDPage firstPage = document.getPage(0);
            PDRectangle mediaBox = firstPage.getMediaBox();
            this.pageHeight = mediaBox.getHeight();
            this.contentWidth = mediaBox.getWidth() - 2 * MARGIN_X;
            open(firstPage);
        }

        void title(String text) throws IOException {
            cursor = TITLE_TOP;
            for (String line : wrap(text, boldFont, TITLE_FONT_SIZE)) {
                float x = MARGIN_X + (contentWidth - width(line, boldFont, TITLE_FONT_SIZE)) / 2;
                draw(line, boldFont, TITLE_FONT_SIZE, TITLE_LINE_HEIGHT, x);
            }
            cursor += TITLE_TO_BODY;
        }

        /**
         * Writes the given texts one below the other, without spacing between them, then adds the paragraph spacing.
         */
        void paragraph(String... texts) throws IOException {
            for (String text : texts) {
                for (String line : wrap(text, regularFont, BODY_FONT_SIZE)) {
                    keepTogether(BODY_LINE_HEIGHT);
                    draw(line, regularFont, BODY_FONT_SIZE, BODY_LINE_HEIGHT, MARGIN_X);
                }
            }
            cursor += PARAGRAPH_SPACING;
        }

        /**
         * Height of the given texts written as one paragraph, without the paragraph spacing.
         */
        float heightOf(String... texts) throws IOException {
            int lines = 0;
            for (String text : texts) {
                lines += wrap(text, regularFont, BODY_FONT_SIZE).size();
            }
            return lines * BODY_LINE_HEIGHT;
        }

        void keepTogether(float height) throws IOException {
            if (cursor + height > pageHeight - MARGIN_Y) {
                PDPage page = new PDPage(PDRectangle.A4);
                document.addPage(page);
                contentStream.close();
                open(page);
                cursor = MARGIN_Y;
            }
        }

        @Override
        public void close() throws IOException {
            contentStream.close();
        }

        private void open(PDPage page) throws IOException {
            contentStream = new PDPageContentStream(document, page, PDPageContentStream.AppendMode.APPEND, true, true);
            contentStream.setNonStrokingColor(0, 0, 0);
        }

        // Breaks the text on spaces. A word wider than the page is cut
        private List<String> wrap(String text, PDType0Font font, float fontSize) throws IOException {
            List<String> lines = new ArrayList<>();
            String line = "";
            for (String word : StringUtils.split(text, ' ')) {
                String candidate = line.isEmpty() ? word : line + " " + word;
                if (width(candidate, font, fontSize) <= contentWidth) {
                    line = candidate;
                    continue;
                }
                if (!line.isEmpty()) {
                    lines.add(line);
                }
                line = word;
                while (width(line, font, fontSize) > contentWidth) {
                    String start = startThatFits(line, font, fontSize);
                    lines.add(start);
                    line = line.substring(start.length());
                }
            }
            if (!line.isEmpty()) {
                lines.add(line);
            }
            return lines;
        }

        // Longest start of the word that fits in the width of the page, one character at least
        private String startThatFits(String word, PDType0Font font, float fontSize) throws IOException {
            StringBuilder start = new StringBuilder();
            for (String grapheme : graphemes(word)) {
                if (!start.isEmpty() && width(start + grapheme, font, fontSize) > contentWidth) {
                    break;
                }
                start.append(grapheme);
            }
            return start.toString();
        }

        private void draw(String line, PDType0Font font, float fontSize, float lineHeight, float x) throws IOException {
            // The text is vertically centered in its line box, as in CSS
            float ascent = font.getFontDescriptor().getAscent() * fontSize / 1000;
            float descent = font.getFontDescriptor().getDescent() * fontSize / 1000;
            float baseline = cursor + (lineHeight - (ascent - descent)) / 2 + ascent;

            contentStream.beginText();
            contentStream.newLineAtOffset(x, pageHeight - baseline);
            for (String grapheme : graphemes(line)) {
                PDType0Font supportedFont = fontFor(grapheme, font);
                if (supportedFont != null) {
                    contentStream.setFont(supportedFont, fontSize);
                    contentStream.showText(grapheme);
                }
            }
            contentStream.endText();
            cursor += lineHeight;
        }

        private float width(String line, PDType0Font font, float fontSize) throws IOException {
            float width = 0;
            for (String grapheme : graphemes(line)) {
                PDType0Font supportedFont = fontFor(grapheme, font);
                if (supportedFont != null) {
                    width += supportedFont.getStringWidth(grapheme) * fontSize / 1000;
                }
            }
            return width;
        }

        // A character missing from every font is skipped and reported
        private PDType0Font fontFor(String grapheme, PDType0Font font) {
            for (PDType0Font candidate : List.of(font, fallbackFont, emojiFont)) {
                if (Utility.isFontSupported(grapheme, candidate)) {
                    return candidate;
                }
            }
            grapheme.codePoints().forEach(codePoint -> skippedCharacters.add(String.format("U+%04X", codePoint)));
            return null;
        }

        // The no-break space has done its job once the lines are known: it is measured and drawn as a space
        private static List<String> graphemes(String text) {
            return GRAPHEME.matcher(text.replace(NO_BREAK_SPACE, ' ')).results().map(MatchResult::group).toList();
        }

        private static PDType0Font load(Fonts font, PDDocument document) throws IOException {
            PDType0Font loadedFont = font.load(document);
            if (loadedFont == null) {
                throw new IOException("Unable to load font " + font);
            }
            return loadedFont;
        }
    }

}
